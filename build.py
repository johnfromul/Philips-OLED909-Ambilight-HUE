from pathlib import Path
import os, subprocess, zipfile

root = Path(__file__).resolve().parent
sdk_value = os.environ.get("ANDROID_SDK_ROOT") or os.environ.get("ANDROID_HOME")
if not sdk_value:
    raise SystemExit("Set ANDROID_SDK_ROOT to your Android SDK directory.")
sdk = Path(sdk_value)
bt = sdk / "build-tools" / os.environ.get("ANDROID_BUILD_TOOLS_VERSION", "36.1.0")
android = sdk / "platforms" / ("android-" + os.environ.get("ANDROID_PLATFORM", "36")) / "android.jar"
keystore = os.environ.get("HUE_KEYSTORE")
if not keystore or not Path(keystore).is_file() or not os.environ.get("HUE_KEYSTORE_PASSWORD"):
    raise SystemExit("Set HUE_KEYSTORE and HUE_KEYSTORE_PASSWORD to your private signing identity.")
for path in [android, *(bt / tool for tool in ("aapt2", "d8", "zipalign", "apksigner"))]:
    if not path.exists():
        raise SystemExit("Missing Android SDK component: " + str(path))
out = root / "build"
for directory in (out, out / "classes", out / "dex"):
    directory.mkdir(parents=True, exist_ok=True)
# Remove stale generated bytecode when rebuilding after source changes.
for pattern in ("classes/**/*.class", "dex/*.dex"):
    for stale in out.glob(pattern):
        stale.unlink()
def run(*args):
    subprocess.run([str(a) for a in args], check=True)
run("javac", "-cp", android, "-d", out / "classes", *sorted((root / "src").rglob("*.java")))
run(bt / "aapt2", "compile", "--dir", root / "res", "-o", out / "resources.zip")
run(bt / "aapt2", "link", "-I", android, "--manifest", root / "AndroidManifest.xml", "-o", out / "base.apk", out / "resources.zip")
run(bt / "d8", "--lib", android, "--output", out / "dex", *sorted((out / "classes").rglob("*.class")))
with zipfile.ZipFile(out / "base.apk", "a") as archive:
    for dex in sorted((out / "dex").glob("*.dex")):
        archive.write(dex, dex.name)
run(bt / "zipalign", "-f", "-p", "4", out / "base.apk", out / "aligned.apk")
sign = [bt / "apksigner", "sign", "--ks", keystore, "--ks-pass", "env:HUE_KEYSTORE_PASSWORD"]
if os.environ.get("HUE_KEY_ALIAS"):
    sign += ["--ks-key-alias", os.environ["HUE_KEY_ALIAS"]]
if os.environ.get("HUE_KEY_PASSWORD"):
    sign += ["--key-pass", "env:HUE_KEY_PASSWORD"]
run(*sign, "--out", out / "ambilight-hue-launcher.apk", out / "aligned.apk")
run(bt / "apksigner", "verify", out / "ambilight-hue-launcher.apk")
print("Built", out / "ambilight-hue-launcher.apk")
